    public const int QUNS_RUNNING_D3D_FULL_SCREEN = 3;
    public const int QUNS_PRESENTATION_MODE = 4;

    [DllImport("shell32.dll")]
    public static extern UIntPtr SHAppBarMessage(uint dwMessage, ref APPBARDATA pData);

    private const uint ABM_GETTASKBARPOS = 0x00000005;

    /// <summary>Taskbar rectangle on the primary monitor in physical pixels.</summary>
    public static RECT? GetTaskbarRect()
    {
        var data = new APPBARDATA { cbSize = Marshal.SizeOf<APPBARDATA>() };
        if (SHAppBarMessage(ABM_GETTASKBARPOS, ref data) == UIntPtr.Zero)
        {
            return null;
        }
        return data.rc;
    }

    public static double ScaleFor(IntPtr hwnd)
    {
        uint dpi = hwnd != IntPtr.Zero ? GetDpiForWindow(hwnd) : 0;
        if (dpi == 0)
        {
            dpi = GetDpiForSystem();
        }
        return dpi / 96.0;
    }
}
